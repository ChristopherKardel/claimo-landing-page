// Builds the customer contact page (kontakt.html, de/kontakt.html, en/kontakt.html).
//
//   node tools/contact/build.mjs
//
// Writes the markup between <!-- CONTACT:START --> and <!-- CONTACT:END --> and
// the page <title> / meta description. Texts: tools/contact/texts.json (DE/EN,
// checked against the app terms 2.7 and the website privacy policy 2.1).
// Styles: assets/css/contact.css. Behaviour: assets/js/contact.js.
//
// This page is for app users only. Business enquiries get their own section.
// The form may only send name, email and message (website privacy policy,
// section 4) — the topic buttons are not form fields, they only pre-fill the
// message. Adding a field means updating the privacy policy first.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TEXTS = JSON.parse(readFileSync(join(ROOT, 'tools/contact/texts.json'), 'utf8'));
const PAGES = [
  { file: 'kontakt.html', lang: 'en' },
  { file: 'de/kontakt.html', lang: 'de' },
  { file: 'en/kontakt.html', lang: 'en' },
];
const START = '<!-- CONTACT:START -->';
const END = '<!-- CONTACT:END -->';
const WEB3FORMS_KEY = 'f07cd476-16e0-45ce-ac39-bfae0c5366aa';
const SUPPORT = 'support@claimo-app.com';

const svg = (d, w = '1.8') => `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${d}</svg>`;
const I = {
  mail: svg('<rect x="3" y="5" width="18" height="14" rx="2.5"/><path d="m3.5 7 8.5 6 8.5-6"/>'),
  phone: svg('<rect x="6.5" y="2.5" width="11" height="19" rx="2.5"/><path d="M10.5 18.5h3"/>'),
  arrowUpRight: svg('<path d="M7 17 17 7"/><path d="M8 7h9v9"/>'),
  arrowRight: svg('<path d="M5 12h14"/><path d="m12 5 7 7-7 7"/>'),
  check: svg('<path d="m5 12.5 4.5 4.5L19 7.5"/>', '2.2'),
};

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
  .replace(/\n/g, '&#10;');
const fill = (s, vars) => s.replace(/\{(\w+)\}/g, (_, k) => {
  if (!(k in vars)) throw new Error(`missing placeholder {${k}} in "${s}"`);
  return vars[k];
});

function build(lang, file) {
  const c = TEXTS[lang];
  const privacyLink = `<a href="datenschutz.html#legal-4">${c.privacyLink}</a>`;

  const topics = c.topics.map(([label, template]) =>
    `<button class="topic" type="button" aria-pressed="false" data-topic="${esc(label)}" data-template="${esc(template)}">${label}</button>`,
  ).join('\n                ');

  const tips = c.tips.map((tip) => `<li>${I.check}<span>${tip}</span></li>`).join('\n              ');

  // the partner page can be switched off (tools/partner/build.mjs) — link it only while it exists
  const links = c.links.filter(([, , href]) => href !== 'partner.html' || existsSync(join(ROOT, dirname(file), href))).map(([title, sub, href]) =>`<li><a class="quick" href="${href}">
                <span class="quick__body"><span class="quick__title">${title}</span><span class="quick__sub">${sub}</span></span>
                ${I.arrowRight}
              </a></li>`).join('\n              ');

  return `${START}
  <!-- ====================== CONTACT (generated by tools/contact/build.mjs) ====================== -->
  <main id="main" class="contact">
    <div class="contact__container">
      <div class="contact__grid">

        <header class="contact__intro">
          <p class="contact__eyebrow">${c.eyebrow}</p>
          <h1 class="contact__title">${c.heading}</h1>
          <p class="contact__lead">${c.lead}</p>
        </header>

        <div class="contact__main">
          <form class="contact-form" id="contact-form" method="post" action="https://api.web3forms.com/submit" data-prefix="${esc(c.topicPrefix)}" data-msg-sending="${esc(c.msgSending)}" data-msg-error="${esc(c.msgError)}">
            <h2 class="contact-form__title">${c.formTitle}</h2>

            <input type="hidden" name="access_key" value="${WEB3FORMS_KEY}">
            <input type="hidden" name="subject" value="${esc(c.formSubject)}">
            <input type="hidden" name="from_name" value="${esc(c.formFromName)}">
            <input class="contact-form__botcheck" type="checkbox" name="botcheck" tabindex="-1" autocomplete="off" aria-hidden="true">

            <fieldset class="topics">
              <legend class="field__label">${c.topicLabel}</legend>
              <div class="topics__list">
                ${topics}
              </div>
            </fieldset>

            <div class="contact-form__row">
              <label class="field">
                <span class="field__label">${c.fieldName}</span>
                <input class="field__input" type="text" name="name" autocomplete="name" required>
              </label>
              <label class="field">
                <span class="field__label">${c.fieldEmail}</span>
                <input class="field__input" type="email" name="email" autocomplete="email" required aria-describedby="email-hint">
                <span class="field__hint" id="email-hint">${c.fieldEmailHint}</span>
              </label>
            </div>
            <label class="field">
              <span class="field__label">${c.fieldMessage}</span>
              <textarea class="field__input" name="message" rows="7" placeholder="${esc(c.fieldMessagePlaceholder)}" required></textarea>
            </label>

            <p class="contact-form__privacy">${fill(c.privacy, { link: privacyLink })}</p>
            <button class="btn btn--primary contact-form__submit" type="submit">${c.submit}</button>
            <p class="contact-form__status" id="contact-status" role="status" aria-live="polite"></p>
          </form>

          <div class="contact-done" id="contact-done" tabindex="-1" hidden>
            <span class="contact-done__icon">${I.check}</span>
            <h2 class="contact-done__title">${c.successTitle}</h2>
            <p class="contact-done__text">${fill(esc(c.successText), { email: '<strong data-email></strong>' })}</p>
            <button class="btn btn--ghost contact-done__again" type="button">${c.successAgain}</button>
          </div>
        </div>

        <div class="contact__info">
          <section class="contact__block" aria-labelledby="contact-direct">
            <h2 class="contact__label" id="contact-direct">${c.directTitle}</h2>
            <ul class="channels">
              <li><a class="channel" href="mailto:${SUPPORT}">
                <span class="channel__icon">${I.mail}</span>
                <span class="channel__body"><span class="channel__title">${c.mailTitle}</span><span class="channel__value">${SUPPORT}</span><span class="channel__sub">${c.mailSub}</span></span>
                <span class="channel__arrow">${I.arrowUpRight}</span>
              </a></li>
              <li><div class="channel channel--static">
                <span class="channel__icon">${I.phone}</span>
                <span class="channel__body"><span class="channel__title">${c.appTitle}</span><span class="channel__value">${c.appValue}</span><span class="channel__sub">${c.appSub}</span></span>
              </div></li>
            </ul>
          </section>

          <section class="contact__block" aria-labelledby="contact-tips">
            <h2 class="contact__label" id="contact-tips">${c.tipsTitle}</h2>
            <ul class="tips">
              ${tips}
            </ul>
          </section>

          <section class="contact__block" aria-labelledby="contact-links">
            <h2 class="contact__label" id="contact-links">${c.linksTitle}</h2>
            <ul class="quicklinks">
              ${links}
            </ul>
          </section>
        </div>

      </div>
    </div>
  </main>
  ${END}`;
}

let changed = 0;
for (const p of PAGES) {
  const path = join(ROOT, p.file);
  const c = TEXTS[p.lang];
  const html = readFileSync(path, 'utf8');
  const s = html.indexOf(START);
  const e = html.indexOf(END);
  if (s === -1 || e === -1 || e < s) throw new Error(`${p.file}: markers ${START} … ${END} not found`);
  let next = html.slice(0, s) + build(p.lang, p.file) + html.slice(e + END.length);
  next = next
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(c.title)}</title>`)
    .replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(c.description)}">`);
  if (next !== html) { writeFileSync(path, next); changed++; }
  console.log(`${p.file}: ${next === html ? 'unchanged' : 'updated'}`);
}
console.log(`${changed} file(s) written`);
