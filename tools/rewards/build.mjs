// Builds the rewards section of the home page ("Prämien", #belohnungen).
//
//   node tools/rewards/build.mjs
//
// Writes the markup between <!-- REWARDS:START --> and <!-- REWARDS:END --> in
// index.html, de/index.html and en/index.html. Texts: tools/rewards/texts.json.
// Styles: assets/css/rewards.css. No JS: the band of cards runs on CSS only.
//
// No partner logos: Claimo has no permission yet to use the logos of PayPal or of
// gift-card brands. The cards are neutral placeholders that name the kind of reward.
// Each kind exists in the app's shop (Rewards-App src/data/mockDashboard.ts):
// cash = PayPal, prepaid = Visa, console = PlayStation / Nintendo,
// appstore = Google Play / Apple, shopping = Amazon / IKEA, fashion = H&M,
// streaming = Netflix, rides = Uber, travel = Airbnb.
// Do not state a number of payout options (no "50+").
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TEXTS = JSON.parse(readFileSync(join(ROOT, 'tools/rewards/texts.json'), 'utf8'));
const PAGES = [
  { file: 'index.html', lang: 'en' },
  { file: 'de/index.html', lang: 'de' },
  { file: 'en/index.html', lang: 'en' },
];
const START = '<!-- REWARDS:START -->';
const END = '<!-- REWARDS:END -->';

// Line icons (24 × 24, stroke) for the placeholder artwork.
const ICONS = {
  cash: '<rect x="2.5" y="6" width="19" height="12" rx="2.5"/><circle cx="12" cy="12" r="2.6"/><path d="M6 9.5v5M18 9.5v5"/>',
  prepaid: '<rect x="2.5" y="5.5" width="19" height="13" rx="2.5"/><path d="M2.5 10h19"/><path d="M6 14.5h4"/>',
  console: '<path d="M6 11h4M8 9v4"/><path d="M15 12h.01M18 10h.01"/><path d="M17.3 5H6.7a4 4 0 0 0-4 3.6L2 15a3 3 0 0 0 5.4 2l1-1.3a2 2 0 0 1 1.6-.7h4a2 2 0 0 1 1.6.7l1 1.3A3 3 0 0 0 22 15l-.7-6.4A4 4 0 0 0 17.3 5z"/>',
  appstore: '<rect x="3" y="3" width="18" height="18" rx="4.5"/><path d="m10 8.5 5 3.5-5 3.5z"/>',
  shopping: '<path d="M5.5 7.5h13l-1 12.5h-11z"/><path d="M9 7.5V7a3 3 0 0 1 6 0v.5"/>',
  fashion: '<path d="M12 6.5a2 2 0 1 0-2-2"/><path d="M12 6.5v1.2L3.6 14a1.4 1.4 0 0 0 .9 2.5h15a1.4 1.4 0 0 0 .9-2.5L12 7.7"/>',
  streaming: '<rect x="2.5" y="4.5" width="19" height="13" rx="2.5"/><path d="M8 21h8"/><path d="m10.5 8.5 4 2.5-4 2.5z"/>',
  rides: '<path d="M19 17h2v-4.2a2 2 0 0 0-.6-1.4L18 9l-1.6-3.2A2 2 0 0 0 14.6 5H9.4a2 2 0 0 0-1.8 1.1L6 9l-2.4 2.4a2 2 0 0 0-.6 1.4V17h2"/><path d="M6 9h12"/><circle cx="7.5" cy="17" r="2"/><circle cx="16.5" cy="17" r="2"/><path d="M9.5 17h5"/>',
  travel: '<rect x="4" y="7.5" width="16" height="12" rx="2.5"/><path d="M9 7.5V5.5a1.5 1.5 0 0 1 1.5-1.5h3A1.5 1.5 0 0 1 15 5.5v2"/><path d="M9 11.5v4M15 11.5v4"/>',
};
// Order in the band and the shop group each kind belongs to.
const CARDS = [
  ['cash', 'money'], ['console', 'games'], ['shopping', 'shopping'], ['streaming', 'leisure'],
  ['prepaid', 'money'], ['appstore', 'games'], ['fashion', 'shopping'], ['travel', 'leisure'], ['rides', 'leisure'],
];

function card(t, [key, group]) {
  return `<li class="rw-card">
              <div class="rw-card__art rw-card__art--${group}"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[key]}</svg></div>
              <p class="rw-card__name">${t.items[key]}</p>
              <p class="rw-card__group">${t.groups[group]}</p>
            </li>`;
}

function build(lang) {
  const t = TEXTS[lang];
  const cards = CARDS.map((c) => card(t, c)).join('\n            ');
  return `${START}
    <!-- ====================== REWARDS (generated by tools/rewards/build.mjs) ====================== -->
    <section class="rw" id="belohnungen" aria-labelledby="rw-title">
      <div class="rw__container rw__head" data-reveal>
        <h2 class="rw__title" id="rw-title">${t.title}</h2>
        <p class="rw__lead">${t.lead}</p>
      </div>
      <div class="rw__band" data-reveal style="--d:120ms">
        <div class="rw__track">
          <ul class="rw__list" aria-label="${t.listLabel}">
            ${cards}
          </ul>
          <ul class="rw__list" aria-hidden="true">
            ${cards}
          </ul>
        </div>
      </div>
      <p class="rw__container rw__note">${t.note}</p>
    </section>
    ${END}`;
}

let changed = 0;
for (const p of PAGES) {
  const path = join(ROOT, p.file);
  const html = readFileSync(path, 'utf8');
  const s = html.indexOf(START);
  const e = html.indexOf(END);
  if (s === -1 || e === -1 || e < s) throw new Error(`${p.file}: markers ${START} … ${END} not found`);
  const next = html.slice(0, s) + build(p.lang) + html.slice(e + END.length);
  if (next !== html) { writeFileSync(path, next); changed++; }
  console.log(`${p.file}: ${next === html ? 'unchanged' : 'updated'}`);
}
console.log(`${changed} file(s) written`);
