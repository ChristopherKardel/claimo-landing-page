// Builds the hero of the home page (variant C of tools/mockups/hero-bonus.html):
// copy left, the real app on the right with an app notification and, small at the
// edge, the app's start-bonus voucher (Rewards-App ClaimoVoucherArtwork).
//
//   node tools/hero/build.mjs
//
// Writes two blocks in index.html, de/index.html and en/index.html:
//   <!-- HERO:START --> … <!-- HERO:END -->              the hero section
//   <!-- HERO-NOTES:START --> … <!-- HERO-NOTES:END -->  its notes, in the footer
// Texts: tools/hero/texts.json (DE/EN). The bonus note follows the app terms 2.7,
// section 6 — change it only after checking it there. Styles: assets/css/hero.css
// (hero) and assets/css/layout.css (.footer__notes).
// Amounts are in euros on every page, because the phone shows the real (euro)
// capture assets/img/screens/games-{de,en}-{540,1080}.webp.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TEXTS = JSON.parse(readFileSync(join(ROOT, 'tools/hero/texts.json'), 'utf8'));
const PAGES = [
  { file: 'index.html', lang: 'en', a: '' },
  { file: 'de/index.html', lang: 'de', a: '../' },
  { file: 'en/index.html', lang: 'en', a: '../' },
];
const DATA = { bonus: 500, reward: 1240, currency: 'EUR' };

const svg = (d) => `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${d}</svg>`;
const arrowDown = svg('<path d="M12 5v14"/><path d="m19 12-7 7-7-7"/>');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const fill = (s, vars) => s.replace(/\{(\w+)\}/g, (_, k) => {
  if (!(k in vars)) throw new Error(`missing placeholder {${k}} in "${s}"`);
  return vars[k];
});

function hero(lang, a) {
  const t = TEXTS[lang];
  const money = (cents) => new Intl.NumberFormat(t.locale, { style: 'currency', currency: DATA.currency, currencyDisplay: 'narrowSymbol' }).format(cents / 100);
  const bonus = money(DATA.bonus);
  const shot = (w) => `${a}assets/img/screens/games-${lang}-${w}.webp`;
  const lines = t.lines.map((line, i) => `<span class="hero__line${i === t.lines.length - 1 ? ' hero__line--accent' : ''}">${line}</span>`);

  return `<!-- HERO:START -->
    <!-- ====================== HERO (generated by tools/hero/build.mjs) ====================== -->
    <section class="hero">
      <div class="hero__container hero__inner">
        <div class="hero__copy">
          <h1 class="hero__title" data-reveal>
            ${lines.join('\n            ')}
          </h1>
          <p class="hero__lead" data-reveal style="--d:120ms">${t.lead}</p>
          <div class="hero__actions" data-reveal style="--d:180ms">
            <a class="btn btn--primary" href="#wie-es-funktioniert">${t.ctaHow} ${arrowDown}</a>
            <a class="btn btn--ghost" href="#belohnungen">${t.ctaRewards}</a>
          </div>
          <p class="hero__facts" data-reveal style="--d:240ms">${t.facts}</p>
        </div>
        <div class="hero__visual" data-reveal style="--d:120ms">
          <div class="hero__device">
            <div class="hero__phone" aria-hidden="true"><div class="hero__screen"><img src="${shot(540)}" srcset="${shot(540)} 540w, ${shot(1080)} 1080w" sizes="(max-width: 640px) 70vw, 300px" width="1344" height="2992" alt="" fetchpriority="high" decoding="async"></div></div>
            <div class="hero__bonus">
              <div class="voucher">
                <img class="voucher__coin" src="${a}assets/img/app/claimo-coin.png" alt="" width="200" height="243">
                <img class="voucher__mark" src="${a}assets/img/claimo-logo.png" alt="Claimo" width="916" height="242">
                <p class="voucher__val"><span class="voucher__label">${t.voucherLabel}</span> <span class="voucher__amt">${bonus}<sup><a href="#fn-bonus" aria-label="${esc(t.footnote)} 1">1</a></sup></span></p>
              </div>
            </div>
            <div class="hero__pop" aria-hidden="true">
              <span class="hero__layer hero__layer--2"></span>
              <span class="hero__layer hero__layer--1"></span>
              <div class="hero__note">
                <img class="hero__note-icon" src="${a}assets/img/app/rok-icon.webp" alt="" width="96" height="96">
                <span class="hero__note-copy">
                  <span class="hero__note-row"><span class="hero__note-title">${t.noteTitle}</span><span class="hero__note-time">${t.noteTime}</span></span>
                  <span class="hero__note-body">${fill(t.noteBody, { amount: money(DATA.reward) })}</span>
                </span>
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
    <!-- HERO:END -->`;
}

function notes(lang) {
  const t = TEXTS[lang];
  const terms = `<a href="nutzungsbedingungen-app.html#legal-6">${t.bonusTerms}</a>`;
  return `<!-- HERO-NOTES:START -->
      <div class="footer__notes" role="note" aria-label="${esc(t.notesLabel)}">
        <p id="fn-bonus"><sup>1</sup> ${fill(t.bonusNote, { terms })}</p>
        <p>${t.screenNote}</p>
      </div>
      <!-- HERO-NOTES:END -->`;
}

function replace(html, file, name, block) {
  const start = `<!-- ${name}:START -->`;
  const end = `<!-- ${name}:END -->`;
  const s = html.indexOf(start);
  const e = html.indexOf(end);
  if (s === -1 || e === -1 || e < s) throw new Error(`${file}: markers ${start} … ${end} not found`);
  return html.slice(0, s) + block + html.slice(e + end.length);
}

let changed = 0;
for (const p of PAGES) {
  const path = join(ROOT, p.file);
  const html = readFileSync(path, 'utf8');
  let next = replace(html, p.file, 'HERO', hero(p.lang, p.a));
  next = replace(next, p.file, 'HERO-NOTES', notes(p.lang));
  if (next !== html) { writeFileSync(path, next); changed++; }
  console.log(`${p.file}: ${next === html ? 'unchanged' : 'updated'}`);
}
console.log(`${changed} file(s) written`);
