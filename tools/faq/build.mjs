// Builds the FAQ section of the home page (design and texts from the new site,
// "claimo-landing-page ALT VERSION": tools/lib/pages/home.mjs faq(), i18n home.faq).
//
//   node tools/faq/build.mjs
//
// Writes the markup between <!-- FAQ:START --> and <!-- FAQ:END --> in index.html,
// de/index.html and en/index.html. Texts: tools/faq/texts.json (DE/EN, checked
// against the app terms 2.7 — change claims only after checking them there).
// Styles: assets/css/faq.css. No JS: the items are native <details> elements.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TEXTS = JSON.parse(readFileSync(join(ROOT, 'tools/faq/texts.json'), 'utf8'));
const PAGES = [
  { file: 'index.html', lang: 'en' },
  { file: 'de/index.html', lang: 'de' },
  { file: 'en/index.html', lang: 'en' },
];
const START = '<!-- FAQ:START -->';
const END = '<!-- FAQ:END -->';

const arrowRight = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M5 12h14"/><path d="m12 5 7 7-7 7"/></svg>';
const fill = (s, vars) => s.replace(/\{(\w+)\}/g, (_, k) => {
  if (!(k in vars)) throw new Error(`missing placeholder {${k}} in "${s}"`);
  return vars[k];
});

function build(lang) {
  const f = TEXTS[lang];
  const deletion = `<a href="konto-loeschen.html">${f.deletionLink}</a>`;
  let first = true;
  const groups = f.groups.map((g) => `<div class="faq-group" data-reveal>
          <h3 class="faq-group__title">${g.title}</h3>
          <div class="faq-group__list">
            ${g.items.map(([q, answer]) => {
              const open = first ? ' open' : '';
              first = false;
              return `<details class="faq-item"${open}>
              <summary>${q}<span class="faq-item__icon" aria-hidden="true"></span></summary>
              <p class="faq-item__answer">${fill(answer, { deletion })}</p>
            </details>`;
            }).join('\n            ')}
          </div>
        </div>`).join('\n        ');

  return `${START}
    <!-- ====================== FAQ (generated by tools/faq/build.mjs) ====================== -->
    <section class="faq" id="faq">
      <div class="faq__container">
        <div class="faq__head" data-reveal>
          <div>
            <h2 class="faq__title">${f.title}</h2>
          </div>
          <div class="faq__help">
            <p>${f.lead}</p>
            <p class="faq__links"><a href="mailto:support@claimo-app.com">support@claimo-app.com</a><a href="kontakt.html">${f.contactLink} ${arrowRight}</a></p>
          </div>
        </div>
        <div class="faq__groups">
        ${groups}
        </div>
      </div>
    </section>
    ${END}`;
}

let changed = 0;
for (const p of PAGES) {
  const path = join(ROOT, p.file);
  const html = readFileSync(path, 'utf8');
  const s = html.indexOf(START);
  const e = html.indexOf(END);
  if (s === -1 || e === -1 || e < s) throw new Error(`${p.file}: markers ${START} … ${END} not found`);
  const next = html.slice(0, s) + build(p.lang) + html.slice(e + END.length);
  if (next !== html) { writeFileSync(path, next); changed++; }
  console.log(`${p.file}: ${next === html ? 'unchanged' : 'updated'}`);
}
console.log(`${changed} file(s) written`);
